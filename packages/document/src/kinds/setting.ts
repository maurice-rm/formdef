declare const SETTING_VALUE: unique symbol

/** What every setting takes. */
type SettingOptions = {
  /** The setting's name in a builder's settings panel. */
  label: string
  /**
   * A description under the name.
   *
   * @defaultValue none
   */
  description?: string
}

/** What a setting that may be left empty or follow an answer takes. */
type ValueSettingOptions<TRequired extends boolean> = SettingOptions & {
  /**
   * Whether the setting must be set.
   *
   * @defaultValue `false`
   */
  required?: TRequired
  /**
   * Whether the setting may follow an answer, through `cases` and `otherwise` in the document.
   *
   * @defaultValue `false`
   */
  varies?: boolean
}

/** The kinds of value a setting holds. */
export type SettingType = 'text' | 'number' | 'boolean' | 'options' | 'date'

/**
 * One setting of a field kind, described as data: what a person may change on a field, with its
 * type and constraints. A builder renders its settings panel from these.
 *
 * @typeParam TValue - The value the setting holds, as the field kind's `props` and `rules` receive
 *   it.
 */
export type Setting<TValue> = {
  /** The kind of value the setting holds. */
  type: SettingType
  /** The setting's name in a builder's settings panel. */
  label: string
  /** A description under the name. */
  description?: string
  /** Whether the setting must be set. */
  required: boolean
  /** Whether the setting may follow an answer. */
  varies: boolean
  /** For text: the most characters. */
  maxLength?: number
  /** For a number: whether it is a whole number. */
  integer?: boolean
  /** For options: the fewest options. */
  minCount?: number
  /** Carries the value type; never set at runtime. */
  readonly [SETTING_VALUE]?: TValue
}

/** One choice of an options setting. */
export type SettingOption = {
  /** The option's key, generated by a builder and never shown. */
  value: string
  /** The option's text. */
  label: string
}

/** The value of a setting that may be left empty. */
type Filled<TValue, TRequired extends boolean> = TRequired extends true
  ? TValue
  : TValue | undefined

/** The settings {@link setting} builds. */
type Settings = {
  /**
   * A line of text, such as a unit or a placeholder.
   *
   * @typeParam TRequired - Whether the setting must be set; without, its value may be `undefined`.
   */
  text: <TRequired extends boolean = false>(
    options: ValueSettingOptions<TRequired> & {
      /**
       * The most characters.
       *
       * @defaultValue no limit
       */
      maxLength?: number
    },
  ) => Setting<Filled<string, TRequired>>
  /**
   * A number, such as a bound.
   *
   * @typeParam TRequired - Whether the setting must be set; without, its value may be `undefined`.
   */
  number: <TRequired extends boolean = false>(
    options: ValueSettingOptions<TRequired> & {
      /**
       * Whether only whole numbers are allowed.
       *
       * @defaultValue `false`
       */
      integer?: boolean
    },
  ) => Setting<Filled<number, TRequired>>
  /**
   * A switch, such as whether a text field has several lines. A document may leave it out, so
   * its value may be `undefined`.
   */
  boolean: (options: SettingOptions) => Setting<boolean | undefined>
  /** The choices of a choice field, each with a generated value and a text; always required. */
  options: (
    options: SettingOptions & {
      /**
       * The fewest options.
       *
       * @defaultValue no limit
       */
      minCount?: number
    },
  ) => Setting<SettingOption[]>
  /**
   * A date as an ISO string, such as the earliest date allowed.
   *
   * @typeParam TRequired - Whether the setting must be set; without, its value may be `undefined`.
   */
  date: <TRequired extends boolean = false>(
    options: ValueSettingOptions<TRequired>,
  ) => Setting<Filled<string, TRequired>>
}

const createSetting = <TValue>(
  type: SettingType,
  {
    required = false,
    varies = false,
    ...rest
  }: SettingOptions & { required?: boolean; varies?: boolean },
): Setting<TValue> => ({ type, ...rest, required, varies })

/**
 * Describes the settings of a field kind: what a person may change on a field of that kind, each
 * with its type and constraints.
 *
 * @example
 * ```ts
 * settings: {
 *   unit: setting.text({ label: 'Unit', required: true, varies: true }),
 *   min: setting.number({ label: 'Minimum' }),
 * }
 * ```
 */
export const setting: Settings = {
  text: (options) => createSetting('text', options),
  number: (options) => createSetting('number', options),
  boolean: (options) => createSetting('boolean', options),
  options: (options) => createSetting('options', { ...options, required: true }),
  date: (options) => createSetting('date', options),
}
