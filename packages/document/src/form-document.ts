import type { Condition } from './condition'
import type { JsonValue } from './json-value'
import type { Text } from './text'
import type { VaryingText } from './varying-text'

/**
 * A setting whose value follows an answer: the value of the first case whose condition holds,
 * otherwise the fallback. Only settings their field kind marks as varying may take this shape.
 */
export type Varying = {
  /** The cases, checked in order. */
  cases: {
    /** The condition under which this case applies. */
    when: Condition
    /** The setting's value in this case. */
    value: JsonValue
  }[]
  /** The setting's value when no case applies. */
  otherwise: JsonValue
}

/**
 * How the form, a step, a section or a row looks: a registered display kind with its settings,
 * which are fixed for the form.
 */
export type Display = {
  /** The name of the display kind. */
  kind: string
  /** The values of the display kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
}

/** A field of a form document: one question, of a registered field kind. */
export type FieldItem = {
  /** Marks the item as a field. */
  type: 'field'
  /** The field's key, unique in the whole document; generated by a builder and never shown. */
  key: string
  /** The name of the field kind the field is of. */
  kind: string
  /** The question shown above the control; it may follow an answer. */
  label: VaryingText
  /** A description between the question and the control; it may follow an answer. */
  description?: VaryingText
  /**
   * Whether the field must be filled in: always, never, or under a condition.
   *
   * @defaultValue `false`
   */
  required?: boolean | Condition
  /** The condition under which the field shows; without it, the field always shows. */
  visibleWhen?: Condition
  /** The values of the field kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
  /**
   * The field's own error texts, by issue code, such as `required`; they win over the project's.
   * A text names the issue's params and the field's label as `{min}` or `{label}`.
   */
  messages?: Record<string, VaryingText>
}

/**
 * Content between fields that gives no answer, such as a notice or a heading: a registered block
 * kind, rendered from its settings.
 */
export type BlockItem = {
  /** Marks the item as a block. */
  type: 'block'
  /** The block's key, unique among the keys of fields and blocks; generated by a builder. */
  key: string
  /** The name of the block kind the block is of. */
  kind: string
  /** The condition under which the block shows; without it, the block always shows. */
  visibleWhen?: Condition
  /** The values of the block kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
}

/** Fields and blocks side by side, as far as the space allows. */
export type RowItem = {
  /** Marks the item as a row. */
  type: 'row'
  /** The condition under which the row shows; without it, the row always shows. */
  visibleWhen?: Condition
  /** How the row looks; without it, as the row slot renders it. */
  display?: Display
  /** The fields and blocks of the row. */
  items: (FieldItem | BlockItem)[]
}

/**
 * A titled group of items. A section inside a section is a group that reads like one question,
 * such as an address; a third level is not allowed.
 */
export type SectionItem = {
  /** Marks the item as a section. */
  type: 'section'
  /** The section's title. */
  label: Text
  /** A description under the title; it may follow an answer. */
  description?: VaryingText
  /** The condition under which the section shows; without it, the section always shows. */
  visibleWhen?: Condition
  /** How the section looks; without it, as the section slot renders it. */
  display?: Display
  /** The items of the section. */
  items: DocumentItem[]
}

/** One item of a form document: a field, a block, a row or a section. */
export type DocumentItem = FieldItem | BlockItem | RowItem | SectionItem

/** One step of a form document filled in one at a time. */
export type DocumentStep = {
  /** The step's key; generated by a builder and never shown. */
  key: string
  /** The step's name in the stepper. */
  label: Text
  /** A line under the step's name; it may follow an answer. */
  description?: VaryingText
  /** The condition under which the step shows; without it, the step always shows. */
  visibleWhen?: Condition
  /** How the step shows in the stepper; without it, as the stepper shows every step. */
  display?: Display
  /** The items of the step. */
  items: DocumentItem[]
}

/** One step or item of a form document, as the edit operations take them. */
export type DocumentNode = DocumentStep | DocumentItem

/**
 * A form described as data: JSON with a format version, for a builder and for forms stored in a
 * database. It holds either steps, filled in one at a time, or the items of a plain form.
 *
 * A document from storage or from a request is read with {@link readDocument}, which checks its shape.
 *
 * @example
 * ```ts
 * const contact: FormDocument = {
 *   format: 1,
 *   items: [{ type: 'field', key: 'f1', kind: 'text', label: 'Name', required: true }],
 * }
 * ```
 */
export type FormDocument =
  | {
      /** The format version the document was written with. */
      format: number
      /**
       * The languages its texts are translated into, as language codes; the first applies when
       * none is chosen. Without it, every text is a string.
       */
      languages?: string[]
      /** How the whole form looks, given to the stepper; without it, as the stepper renders. */
      display?: Display
      /** The steps, in order. */
      steps: DocumentStep[]
      /** A document with steps holds its items in them. */
      items?: never
    }
  | {
      /** The format version the document was written with. */
      format: number
      /**
       * The languages its texts are translated into, as language codes; the first applies when
       * none is chosen. Without it, every text is a string.
       */
      languages?: string[]
      /**
       * How the whole form looks, which applies to a form of steps only; `checkDocument` reports
       * one here.
       */
      display?: Display
      /** The items of a form without steps, in order. */
      items: DocumentItem[]
      /** A document without steps holds no steps. */
      steps?: never
    }
