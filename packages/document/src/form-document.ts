import type { Condition } from './condition'
import type { Expression } from './expression'
import type { JsonValue } from './json-value'
import type { Text } from './text'
import type { VaryingText } from './varying-text'

/**
 * A setting whose value follows an answer: the value of the first case whose condition holds,
 * otherwise the fallback. Only settings their field kind marks as varying may take this shape.
 */
export type Varying = {
  /** The cases, checked in order. */
  cases: {
    /** The condition under which this case applies. */
    when: Condition
    /** The setting's value in this case. */
    value: JsonValue
  }[]
  /** The setting's value when no case applies. */
  otherwise: JsonValue
}

/**
 * How the form, a step, a section, a row or a repeat looks: a registered display kind with its
 * settings, which are fixed for the form.
 */
export type Display = {
  /** The name of the display kind. */
  kind: string
  /** The values of the display kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
}

/**
 * A check of a field against other answers: it passes when its condition holds, which may compare
 * the field itself, such as with `valueFrom`.
 */
export type Check = {
  /** The condition the answer has to meet. */
  when: Condition
  /** The error text when it does not; it may name answers as `{key}` and follow an answer. */
  message?: VaryingText
}

/** A field of a form document: one question, of a registered field kind. */
export type FieldItem = {
  /** Marks the item as a field. */
  type: 'field'
  /** The field's key, unique in the whole document; generated by a builder and never shown. */
  key: string
  /** The name of the field kind the field is of. */
  kind: string
  /** The question shown above the control; it may follow an answer. */
  label: VaryingText
  /** A description between the question and the control; it may follow an answer. */
  description?: VaryingText
  /**
   * Whether the field must be filled in: always, never, or under a condition.
   *
   * @defaultValue `false`
   */
  required?: boolean | Condition
  /** The condition under which the field shows; without it, the field always shows. */
  visibleWhen?: Condition
  /** The values of the field kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
  /**
   * The field's own error texts, by issue code, such as `required`; they win over the project's.
   * A text names the issue's params and the field's label as `{min}` or `{label}`.
   */
  messages?: Record<string, VaryingText>
  /**
   * Checks against other answers, after the field kind's rules and only for a filled field; the
   * first that fails is reported with the code `check`.
   */
  checks?: Check[]
}

/**
 * Content between fields that gives no answer, such as a notice or a heading: a registered block
 * kind, rendered from its settings.
 */
export type BlockItem = {
  /** Marks the item as a block. */
  type: 'block'
  /** The block's key, unique among the keys of fields and blocks; generated by a builder. */
  key: string
  /** The name of the block kind the block is of. */
  kind: string
  /** The condition under which the block shows; without it, the block always shows. */
  visibleWhen?: Condition
  /** The values of the block kind's settings, by setting name. */
  settings?: Record<string, JsonValue | Varying>
}

/**
 * A value worked out from earlier answers, which nobody types: conditions compare it and
 * placeholders name it like an answer, and the validator's answers hold it, computed again.
 */
export type ComputedItem = {
  /** Marks the item as a computed value. */
  type: 'computed'
  /** The computed value's key, unique among the keys of fields, blocks and computed values. */
  key: string
  /** What the value is called; it may follow an answer. */
  label: VaryingText
  /** The name of the value type of its result: `number`, `text` or `date`. */
  valueType: string
  /** How the value is worked out. */
  expression: Expression
  /** The condition under which the value counts; without it, it always counts. */
  visibleWhen?: Condition
}

/** Fields, blocks and computed values side by side, as far as the space allows. */
export type RowItem = {
  /** Marks the item as a row. */
  type: 'row'
  /** The condition under which the row shows; without it, the row always shows. */
  visibleWhen?: Condition
  /** How the row looks; without it, as the row slot renders it. */
  display?: Display
  /** The fields, blocks and computed values of the row. */
  items: (FieldItem | BlockItem | ComputedItem)[]
}

/**
 * A titled group of items. A section inside a section is a group that reads like one question,
 * such as an address; a third level is not allowed.
 */
export type SectionItem = {
  /** Marks the item as a section. */
  type: 'section'
  /** The section's title. */
  label: Text
  /** A description under the title; it may follow an answer. */
  description?: VaryingText
  /** The condition under which the section shows; without it, the section always shows. */
  visibleWhen?: Condition
  /** How the section looks; without it, as the section slot renders it. */
  display?: Display
  /** The items of the section. */
  items: DocumentItem[]
}

/**
 * Items that repeat as entries, as often as the person needs, such as one block per resident. Its
 * value is a list of entries; inside it, a condition, placeholder or expression that names a
 * field of the repeat reads that field of the same entry. A repeat holds no other repeat.
 */
export type RepeatItem = {
  /** Marks the item as a repeat. */
  type: 'repeat'
  /** The repeat's key, which its list of entries sits under; unique among the keys of fields. */
  key: string
  /** The repeat's title. */
  label: Text
  /** The label of the button that adds an entry. */
  addLabel: Text
  /** The label of the button that removes an entry; `{n}` names the entry's number. */
  removeLabel: Text
  /** The title of each entry, such as `Person {n}`; `{n}` names the entry's number. */
  entryLabel?: Text
  /**
   * The fewest entries.
   *
   * @defaultValue `0`
   */
  min?: number
  /** The most entries; without it, as many as the person needs. */
  max?: number
  /** The condition under which the repeat shows; without it, the repeat always shows. */
  visibleWhen?: Condition
  /** How the entries look; without it, as the array frame slot renders them. */
  display?: Display
  /** The items of each entry. */
  items: DocumentItem[]
}

/** One item of a form document: a field, a block, a computed value, a row, a section or a repeat. */
export type DocumentItem = FieldItem | BlockItem | ComputedItem | RowItem | SectionItem | RepeatItem

/**
 * A jump from a step, when the person moves on and its condition holds: forward to a later step,
 * so the steps up to it do not show, or to an ending, so the form is submitted and the steps after
 * it do not show.
 */
export type Jump =
  | {
      /** The condition, on the answers of the step and those before it. */
      when: Condition
      /** The key of a later step the form goes on with. */
      step: string
      /** A jump goes to a step or ends the form, not both. */
      end?: never
    }
  | {
      /** The condition, on the answers of the step and those before it. */
      when: Condition
      /** The key of the ending the form ends with. */
      end: string
      /** A jump goes to a step or ends the form, not both. */
      step?: never
    }

/**
 * What a person sees once the form is submitted: blocks whose texts may name answers. An ending a
 * jump names applies only through its jump. Of the others, the first whose condition holds
 * applies; one without a condition is the fallback and comes last among them.
 */
export type Ending = {
  /** The ending's key, which a jump that ends the form names. */
  key: string
  /** The condition under which the ending applies; without it, it is the fallback. */
  when?: Condition
  /** The blocks the ending shows. */
  items: BlockItem[]
}

/**
 * What a person sees before the form: blocks of fixed text, which name no answers, and the label
 * of the button that starts the form.
 */
export type Intro = {
  /** The blocks the intro shows. */
  items: BlockItem[]
  /** The label of the button that starts the form. */
  start: Text
}

/** One step of a form document filled in one at a time. */
export type DocumentStep = {
  /** The step's key; generated by a builder and never shown. */
  key: string
  /** What the stepper shows for the step. */
  label: Text
  /** A line under the step's name; it may follow an answer. */
  description?: VaryingText
  /** The condition under which the step shows; without it, the step always shows. */
  visibleWhen?: Condition
  /** How the step shows in the stepper; without it, as the stepper shows every step. */
  display?: Display
  /**
   * Jumps forward, checked in order when the person moves on; the first whose condition holds
   * applies. Without one that holds, the next step that shows follows.
   */
  next?: Jump[]
  /** The items of the step. */
  items: DocumentItem[]
}

/** One step or item of a form document, as the edit operations take them. */
export type DocumentNode = DocumentStep | DocumentItem

/**
 * A form described as data: JSON with a format version, for a builder and for forms stored in a
 * database. It holds either steps, filled in one at a time, or the items of a plain form.
 *
 * A document from storage or from a request is read with {@link readDocument}, which checks its shape.
 *
 * @example
 * ```ts
 * const contact: FormDocument = {
 *   format: 1,
 *   items: [{ type: 'field', key: 'f1', kind: 'text', label: 'Name', required: true }],
 * }
 * ```
 */
export type FormDocument =
  | {
      /** The format version the document was written with. */
      format: number
      /**
       * The languages its texts are translated into, as language codes; the first applies when
       * none is chosen. Without it, every text is a string.
       */
      languages?: string[]
      /** How the whole form looks, given to the stepper; without it, as the stepper renders. */
      display?: Display
      /** What a person sees before the form, with the button that starts it. */
      intro?: Intro
      /** What a person sees once the form is submitted, as {@link Ending} describes. */
      endings?: Ending[]
      /**
       * The label of a submit button, which applies to a form without steps only; the stepper
       * submits a form of steps, and `checkDocument` reports one here.
       */
      submit?: Text
      /** The steps, in order. */
      steps: DocumentStep[]
      /** A document with steps holds its items in them. */
      items?: never
    }
  | {
      /** The format version the document was written with. */
      format: number
      /**
       * The languages its texts are translated into, as language codes; the first applies when
       * none is chosen. Without it, every text is a string.
       */
      languages?: string[]
      /**
       * How the whole form looks, which applies to a form of steps only; `checkDocument` reports
       * one here.
       */
      display?: Display
      /** What a person sees before the form, with the button that starts it. */
      intro?: Intro
      /** What a person sees once the form is submitted, as {@link Ending} describes. */
      endings?: Ending[]
      /**
       * The label of the submit button after the items; without it, the form renders none and
       * the project places its own.
       */
      submit?: Text
      /** The items of a form without steps, in order. */
      items: DocumentItem[]
      /** A document without steps holds no steps. */
      steps?: never
    }
